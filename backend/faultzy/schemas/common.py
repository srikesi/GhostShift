"""Shared contract primitives used by every stage and API response."""

from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum

from pydantic import BaseModel, ConfigDict, Field


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


class Contract(BaseModel):
    """Base for all Faultzy contracts: unknown fields are rejected."""

    model_config = ConfigDict(extra="forbid", use_enum_values=False)


class DataSource(str, Enum):
    """Provenance of a value. Raw, derived and simulated values never mix."""

    measured = "measured"  # raw observation from a real sensor/dataset
    simulated = "simulated"  # generated by a fixture or simulation
    derived = "derived"  # computed by Faultzy from upstream values
    fixture = "fixture"  # static reference data shipped with the demo
    external = "external"  # returned by a real external system
    llm = "llm"  # generated by a language model


class Provenance(Contract):
    source: DataSource
    detail: str = Field(description="Human-readable origin, e.g. dataset or fixture file")
    upstream_source: DataSource | None = Field(
        default=None,
        description="For derived values: provenance of the inputs (e.g. derived from simulated telemetry)",
    )


class StageStatus(str, Enum):
    success = "success"
    deterministic_fallback = "deterministic_fallback"
    provider_failure = "provider_failure"
    invalid_result = "invalid_result"
    skipped = "skipped"


class ProviderKind(str, Enum):
    deterministic = "deterministic"  # in-process rule/maths implementation
    stub = "stub"  # simulated stand-in for an external system
    external = "external"  # real third-party / AWS service


class ProviderInfo(Contract):
    name: str
    kind: ProviderKind
    real: bool
    model_id: str | None = None


class Severity(str, Enum):
    normal = "normal"
    watch = "watch"
    warning = "warning"
    critical = "critical"

    @property
    def rank(self) -> int:
        return _SEVERITY_RANK[self]


_SEVERITY_RANK = {Severity.normal: 0, Severity.watch: 1, Severity.warning: 2, Severity.critical: 3}


class ErrorBody(Contract):
    code: str
    message: str
    details: dict | None = None


class ErrorResponse(Contract):
    error: ErrorBody
